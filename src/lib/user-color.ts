// Стабильный цвет + инициалы для сотрудника — цветной кружок с буквами,
// чтобы узнавать человека в графике с первого взгляда, не читая имя целиком.

// Порядок специально подобран так, чтобы первые несколько цветов были
// максимально непохожи друг на друга (тёплый/холодный вперемешку) — команда
// маленькая (5-8 человек), и именно первые цвета в списке чаще всего и
// достаются реальным сотрудникам.
const PALETTE = [
  "bg-emerald-500",
  "bg-rose-500",
  "bg-sky-500",
  "bg-amber-500",
  "bg-violet-500",
  "bg-fuchsia-500",
  "bg-teal-500",
  "bg-indigo-500",
];

function hashStr(s: string): number {
  let h = 0;
  for (let i = 0; i < s.length; i++) {
    h = (h * 31 + s.charCodeAt(i)) >>> 0;
  }
  return h;
}

// Резервный вариант (по хэшу id) — используется, только если пользователя нет
// в переданной карте цветов (например, уволенный сотрудник из старой записи).
export function userColor(userId: string): string {
  return PALETTE[hashStr(userId) % PALETTE.length];
}

// Основной способ назначения цвета: каждому активному пользователю — свой
// цвет по порядковому номеру в списке (а не по хэшу id), чтобы при небольшом
// числе сотрудников (как сейчас) цвета гарантированно не повторялись и не
// оказывались случайно похожими друг на друга (два оттенка фиолетового и
// т.п.). Порядок списка должен быть стабильным между рендерами — вызывающий
// код передаёт пользователей, отсортированных по дате создания.
export function buildUserColorMap(orderedUserIds: string[]): Record<string, string> {
  const map: Record<string, string> = {};
  orderedUserIds.forEach((id, i) => {
    map[id] = PALETTE[i % PALETTE.length];
  });
  return map;
}

// Инициалы для одного слова — берём 3 буквы, а не 2: у нас несколько имён
// начинаются на одинаковые две буквы (Айзада/Айгерим), а на трёх буквах они
// уже расходятся (АЙЗ/АЙГ). Для имени из двух слов по-прежнему берём по
// первой букве каждого — там коллизии куда менее вероятны.
export function initials(name: string): string {
  const parts = name.trim().split(/\s+/).filter(Boolean);
  if (parts.length === 0) return "?";
  if (parts.length === 1) return parts[0].slice(0, 3).toUpperCase();
  return (parts[0][0] + parts[1][0]).toUpperCase();
}
